import java.nio.charset.StandardCharsets;
import java.nio.file.*;
import java.util.*;

/** Run from project root: java DATA/GenerateDemoSeed.java. Does not connect to SQL. */
public final class GenerateDemoSeed {
    private final StringBuilder sql = new StringBuilder();
    private final Map<String, List<String[]>> groups = new LinkedHashMap<>();

    public static void main(String[] args) throws Exception {
        new GenerateDemoSeed().generate();
    }

    private String text(String value) {
        return "N'" + value.replace("'", "''") + "'";
    }

    private void line(String value) {
        sql.append(value).append('\n');
    }

    private void generate() throws Exception {
        for (String kind : List.of("NV", "TK", "DV", "HH", "PK"))
            groups.put(kind, new ArrayList<>());
        for (String row : Files.readAllLines(Path.of("src/main/resources/demo/dataset.tsv"),
                StandardCharsets.UTF_8)) {
            if (row.isBlank() || row.startsWith("#"))
                continue;
            String[] fields = row.split("\t", -1);
            groups.get(fields[0]).add(fields);
        }
        line("""
                -- GENERATED by DATA/GenerateDemoSeed.java from demo/dataset.tsv.
                -- RESET: DELETE ALL DATA in the 7 Duy tables, then load synchronized demo data.
                -- Only N15_DUY_DB or N15_DUY_TEST_* is allowed. Errors roll back the whole reset.
                SET XACT_ABORT ON;
                SET NOCOUNT ON;
                SET QUOTED_IDENTIFIER ON;
                SET ANSI_NULLS ON;
                IF DB_NAME()<>'N15_DUY_DB' AND LEFT(DB_NAME(),13)<>'N15_DUY_TEST_'
                    THROW 51000,'Wrong database: only reset the Duy demo database.',1;
                BEGIN TRY
                BEGIN TRANSACTION;
                DELETE FROM dbo.ChiDinhDichVu;
                DELETE FROM dbo.PhieuKham;
                DELETE FROM dbo.TaiKhoan;
                DELETE FROM dbo.NhanVien;
                DELETE FROM dbo.DichVu;
                DELETE FROM dbo.HangHoa;
                DELETE FROM dbo.DuyBoDem;
                """);
        for (String[] r : groups.get("NV")) {
            line("INSERT INTO dbo.NhanVien(maNhanVien,hoTen,soDienThoai,ngaySinh,gioiTinh,cccd,chucVu,conLamViec) VALUES("
                    + String.join(",", text(r[1]), text(r[2]), text(r[3]), text(r[4]),
                            r[5].equals("true") ? "1" : "0", text(r[6]), text(r[7]),
                            r[8].equals("true") ? "1" : "0")
                    + ");");
        }
        line("INSERT INTO dbo.DuyBoDem(khoa,giaTri) VALUES('TK260101',0);\nDECLARE @id varchar(12),@n int;");
        for (String[] r : groups.get("TK")) {
            line("UPDATE dbo.DuyBoDem WITH(UPDLOCK,HOLDLOCK) SET giaTri=giaTri+1 WHERE khoa='TK260101';");
            line("SELECT @n=giaTri FROM dbo.DuyBoDem WHERE khoa='TK260101';");
            line("SET @id='TK260101'+RIGHT('0000'+CAST(@n AS varchar(4)),4);");
            line("INSERT INTO dbo.TaiKhoan(maTaiKhoan,matKhau,trangThai,maNhanVien) VALUES(@id,CONVERT(varchar(64),HASHBYTES('SHA2_256','123456'),2),"
                    + text(r[2]) + "," + text(r[1]) + ");");
        }
        for (String[] r : groups.get("DV"))
            line("INSERT INTO dbo.DichVu VALUES(" + String.join(",", text(r[1]), text(r[2]), r[3], text(r[4]))
                    + ");");
        for (String[] r : groups.get("HH"))
            line("INSERT INTO dbo.HangHoa VALUES("
                    + String.join(",", text(r[1]), text(r[2]), text(r[3]), r[4], r[5]) + ");");
        for (String[] r : groups.get("PK")) {
            line("INSERT INTO dbo.PhieuKham(maPhieuKham,ngayKham,trangThai,maNhanVien) VALUES(" + String.join(
                    ",", text(r[1]), "DATEADD(day,-" + Integer.parseInt(r[2]) + ",CAST(GETDATE() AS date))",
                    text(r[3]), text(r[4])) + ");");
            for (String service : r[5].split(","))
                line("INSERT INTO dbo.ChiDinhDichVu VALUES(" + text(r[1]) + "," + text(service) + ");");
        }
        for (String kind : List.of("NV", "DV", "HH")) {
            int cut = kind.equals("DV") ? 2 : 8;
            int maximum = groups.get(kind).stream().mapToInt(r -> Integer.parseInt(r[1].substring(cut))).max()
                    .orElse(0);
            String key = kind.equals("DV") ? "DV" : kind + "260101";
            line("INSERT INTO dbo.DuyBoDem(khoa,giaTri) VALUES(" + text(key) + "," + maximum + ");");
        }
        line("""
                COMMIT;
                END TRY
                BEGIN CATCH
                    IF @@TRANCOUNT>0 ROLLBACK;
                    THROW;
                END CATCH;
                SELECT t.maTaiKhoan,n.hoTen,n.chucVu,t.trangThai,n.conLamViec
                FROM dbo.TaiKhoan t JOIN dbo.NhanVien n ON n.maNhanVien=t.maNhanVien ORDER BY t.maTaiKhoan;
                GO
                """);
        Files.writeString(Path.of("DATA/seed/001_duy_demo.sql"), sql, StandardCharsets.UTF_8);
        groups.forEach((kind, rows) -> System.out.println(kind + ": " + rows.size()));
    }
}
